export type Lang = 'en' | 'ar';
const DICTS: Record<Lang, Record<Key, string>> = { en, ar };

export type T = (key: Key, vars?: Record<string, string | number>) => string;

interface I18n { lang: Lang; setLang: (l: Lang) => void; t: T; has: (key: string) => key is Key }
const Ctx = createContext<I18n | null>(null);

function stored(): Lang {
  try { return localStorage.getItem('nb.lang') === 'ar' ? 'ar' : 'en'; } catch { return 'en'; }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(stored);
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.title = DICTS[lang]['app.name'];
  }, [lang]);
  const value = useMemo<I18n>(() => ({
    lang,
    setLang: (l) => { setLangState(l); try { localStorage.setItem('nb.lang', l); } catch { /* private mode */ } },
    t: (key, vars) => {
      let s = DICTS[lang][key] ?? en[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
      return s;
    },
    has: (key: string): key is Key => key in en,
  }), [lang]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error('useI18n outside I18nProvider');
  return v;
}

/** Picks the Arabic name when the UI is in Arabic and one exists. */
export function useLocalName() {
  const { lang } = useI18n();
  return (name: string | null | undefined, nameAr: string | null | undefined) => (lang === 'ar' && nameAr ? nameAr : name ?? '');
}
